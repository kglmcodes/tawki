/* Tawki — mobile-first study UI. Vanilla JS, offline-capable.
   Data: web/data/index.json + web/data/<lang>.json (generated by scripts/build_data.py)

   Scheduling is a small Leitner ladder: each word sits in a box; grading moves
   it and sets a due date. Box 0 = relearn (10 min) up to box 5 (35 days).
   A word counts as "known" once it reaches box 3. */

const LESSON_SIZE = 20;
const BOX_MINUTES = [10, 24 * 60, 3 * 24 * 60, 7 * 24 * 60, 16 * 24 * 60, 35 * 24 * 60];
const KNOWN_BOX = 3;
const SPK = `<svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true"><path fill="currentColor" d="M4 9v6h4l5 4V5L8 9H4zm12.5 3a4.5 4.5 0 0 0-2-3.74v7.48A4.5 4.5 0 0 0 16.5 12z"/></svg>`;

const state = {
  lang: null,
  data: null,
  sched: {},            // rank -> { b: box, d: dueMs, r: reps, l: lapses }
  view: "learn",
  learnTab: "vocab",
  query: "",
  hideKnown: false,
  scope: "due",         // "due" | "all" | "lesson:<n>"
  mode: "recognition",  // "recognition" | "production" | "quiz"
  notation: "both",     // "both" | "zhuyin" | "pinyin"
  frontPron: "show",    // "show" | "hide" — reading on the hidden side
  shuffle: false,
  deck: [],
  deckPos: 0,
  flipped: false,
  quizPicked: null,
};

const $ = (s) => document.querySelector(s);
const $$ = (s) => document.querySelectorAll(s);
const key = (lang) => `tawki:${lang}`;
const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) =>
  ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const isCJK = (s) => /[\u3400-\u9FFF\uF900-\uFAFF]/.test(s);
const wordClass = (w) => "word" + (isCJK(w) ? " word-cjk" : "");
const zhPart = (s) => String(s || "").split(/[(（]/)[0].trim();
const cap = (x, lo, hi) => Math.max(lo, Math.min(hi, x));
const toneHTML = (parts, sep) =>
  Array.isArray(parts) && parts.length
    ? parts.map((p) => `<span class="tn t${p.tone}">${esc(p.text)}</span>`).join(sep)
    : "";

/* ---------- persistence ---------- */
function load(lang) {
  state.sched = {};
  try {
    const raw = JSON.parse(localStorage.getItem(key(lang)) || "{}");
    if (raw.sched) {
      state.sched = raw.sched;
    } else if (Array.isArray(raw.known)) {
      for (const r of raw.known) state.sched[r] = { b: 5, d: Date.now() + 35 * 864e5, r: 1 };
    }
  } catch { state.sched = {}; }
}
function save() {
  localStorage.setItem(key(state.lang), JSON.stringify({ sched: state.sched }));
}

/* ---------- notation (Zhuyin / Pinyin / both) ---------- */
const NOTATION_KEY = "tawki:notation";
function loadNotation() {
  const v = localStorage.getItem(NOTATION_KEY);
  if (v === "zhuyin" || v === "pinyin" || v === "both") state.notation = v;
}
function applyNotation() {
  document.body.classList.toggle("only-zhuyin", state.notation === "zhuyin");
  document.body.classList.toggle("only-pinyin", state.notation === "pinyin");
  const sel = $("#notation");
  if (sel) sel.value = state.notation;
}

/* ---------- reading on the hidden (front) side ---------- */
const FRONT_PRON_KEY = "tawki:front-pron";
function loadFrontPron() {
  const v = localStorage.getItem(FRONT_PRON_KEY);
  if (v === "show" || v === "hide") state.frontPron = v;
}
function applyFrontPron() {
  const btn = $("#front-pron");
  if (!btn) return;
  const shown = state.frontPron === "show";
  btn.setAttribute("aria-pressed", String(shown));
  btn.textContent = shown ? "Reading: shown" : "Reading: hidden";
}

/* ---------- progress backup (export / import) ---------- */
function exportProgress() {
  const data = {};
  for (let i = 0; i < localStorage.length; i++) {
    const k = localStorage.key(i);
    if (k && k.startsWith("tawki:")) data[k] = localStorage.getItem(k);
  }
  const payload = { app: "tawki", exported: new Date().toISOString(), data };
  const blob = new Blob([JSON.stringify(payload, null, 1)], { type: "application/json" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = `tawki-progress-${new Date().toISOString().slice(0, 10)}.json`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(a.href);
}

function importProgress(file) {
  const reader = new FileReader();
  reader.onload = () => {
    try {
      const parsed = JSON.parse(reader.result);
      const data = parsed.data || parsed;
      let n = 0;
      for (const [k, v] of Object.entries(data)) {
        if (k.startsWith("tawki:")) {
          localStorage.setItem(k, typeof v === "string" ? v : JSON.stringify(v));
          n += 1;
        }
      }
      alert(`Imported ${n} entries. Reloading.`);
      location.reload();
    } catch {
      alert("That file could not be read as a Tawki progress export.");
    }
  };
  reader.readAsText(file);
}
const schedOf = (rank) => state.sched[rank];
const isKnown = (rank) => (schedOf(rank)?.b ?? -1) >= KNOWN_BOX;
const isDue = (rank) => { const s = schedOf(rank); return !s || s.d <= Date.now(); };
const isNew = (rank) => !schedOf(rank);
function grade(rank, g) {
  const s = schedOf(rank) || { b: 0, d: 0, r: 0, l: 0 };
  if (g === "again") { s.b = 0; s.l = (s.l || 0) + 1; }
  else if (g === "hard") { s.b = cap(s.b ?? 0, 0, 5); }
  else if (g === "good") { s.b = cap((s.b ?? 0) + 1, 0, 5); }
  else if (g === "easy") { s.b = cap((s.b ?? 0) + 2, 0, 5); }
  s.r = (s.r || 0) + 1;
  s.d = Date.now() + BOX_MINUTES[s.b] * 60000;
  state.sched[rank] = s;
  save();
}
function toggleKnown(rank, on) {
  if (on) state.sched[rank] = { b: 5, d: Date.now() + 35 * 864e5, r: (schedOf(rank)?.r || 0) + 1 };
  else delete state.sched[rank];
  save();
}

/* ---------- speech ---------- */
let VOICE = null;
function pickVoice() {
  if (!("speechSynthesis" in window)) return;
  const vs = speechSynthesis.getVoices();
  VOICE = vs.find((v) => /zh[-_]TW/i.test(v.lang)) || vs.find((v) => /^zh/i.test(v.lang)) || null;
}
function speak(text) {
  const t = zhPart(text);
  if (!t || !("speechSynthesis" in window)) return;
  speechSynthesis.cancel();
  const u = new SpeechSynthesisUtterance(t);
  u.lang = "zh-TW";
  if (VOICE) u.voice = VOICE;
  u.rate = 0.9;
  speechSynthesis.speak(u);
}
function spkBtn(text, label) {
  const b = document.createElement("button");
  b.type = "button";
  b.className = "spk";
  b.title = "Pronounce";
  b.innerHTML = SPK + (label ? `<span>${esc(label)}</span>` : "");
  b.addEventListener("click", (e) => { e.stopPropagation(); speak(text); });
  return b;
}
function fillSpeakbar(el, items) {
  el.innerHTML = "";
  for (const { text, label } of items) if (text) el.appendChild(spkBtn(text, label));
}

/* ---------- lessons ---------- */
function lessons() {
  const out = [];
  for (let i = 0; i < state.data.vocab.length; i += LESSON_SIZE) {
    out.push({ n: out.length + 1, items: state.data.vocab.slice(i, i + LESSON_SIZE) });
  }
  return out;
}
const knownIn = (items) => items.filter((v) => isKnown(v.rank)).length;

/* ---------- Learn / Vocabulary ---------- */
function renderLearnVocab() {
  const grid = $("#lesson-grid");
  const list = $("#vocab-list");
  const meta = $("#browse-meta");
  const q = state.query.trim().toLowerCase();

  if (q) {
    grid.hidden = true;
    list.hidden = false;
    const items = state.data.vocab.filter((v) =>
      !(state.hideKnown && isKnown(v.rank)) &&
      (v.word + " " + v.pinyin + " " + v.meaning).toLowerCase().includes(q));
    list.innerHTML = "";
    for (const v of items) list.appendChild(vocabCard(v));
    meta.textContent = `${items.length} match · ${state.sched ? Object.keys(state.sched).length : 0} tracked`;
    return;
  }

  list.hidden = true;
  grid.hidden = false;
  const tracked = Object.keys(state.sched).length;
  meta.textContent = `${knownIn(state.data.vocab)} known · ${tracked} tracked · ${state.data.vocab.length} total`;
  grid.innerHTML = "";
  for (const l of lessons()) {
    const k = knownIn(l.items);
    const pct = Math.round((k / l.items.length) * 100);
    const b = document.createElement("button");
    b.className = "lesson" + (k === l.items.length ? " is-done" : "");
    b.innerHTML = `
      <div class="lesson-top"><span class="lesson-no">Lesson ${l.n}</span>
        <span class="lesson-count">${k}/${l.items.length}</span></div>
      <div class="lesson-sample">${l.items.slice(0, 5).map((v) => esc(v.word)).join(" ")}</div>
      <div class="bar"><span style="width:${pct}%"></span></div>`;
    b.addEventListener("click", () => { state.scope = `lesson:${l.n}`; buildScopeOptions(); showView("practice"); });
    grid.appendChild(b);
  }
}

function vocabCard(v) {
  const li = document.createElement("li");
  li.className = "card vocab-row" + (isKnown(v.rank) ? " is-known" : "");
  li.innerHTML = `
    <span class="rank">${v.rank}</span>
    <div class="vocab-main">
      <div><span class="${wordClass(v.word)}">${esc(v.word)}</span>
        <span class="zhuyin">${toneHTML(v.zhuyinParts, " ") || esc(v.zhuyin)}</span>
        <span class="pinyin">${toneHTML(v.pinyinParts, "") || esc(v.pinyin)}</span></div>
      <div>${esc(v.meaning)}</div>
      <div class="example">${esc(v.example)}</div>
      <div class="speakbar"></div>
    </div>
    <button class="mark" title="Toggle known" aria-label="Toggle known">&#10003;</button>`;
  fillSpeakbar(li.querySelector(".speakbar"), [
    { text: v.word, label: "Word" },
    { text: v.example, label: "Sentence" },
  ]);
  const toggle = () => {
    toggleKnown(v.rank, !isKnown(v.rank));
    renderLearnVocab();
    if (state.view === "progress") renderProgress();
  };
  li.querySelector(".mark").addEventListener("click", (e) => { e.stopPropagation(); toggle(); });
  li.addEventListener("click", toggle);
  return li;
}

/* ---------- Learn / Patterns ---------- */
function renderPatterns() {
  const list = $("#pattern-list");
  list.innerHTML = "";
  for (const p of state.data.patterns) {
    const li = document.createElement("li");
    li.className = "card";
    const ex = p.examples.length
      ? `<ul class="pattern-examples">${p.examples.map((e) => `<li>${esc(e)}</li>`).join("")}</ul>`
      : "";
    li.innerHTML = `
      <div class="pattern-head"><span class="pattern-num">${p.n}</span>
        <span class="pattern-name">${esc(p.name)}</span></div>
      ${p.does ? `<div>${esc(p.does)}</div>` : ""}
      ${p.structure ? `<div class="pattern-structure">${esc(p.structure)}</div>` : ""}
      ${ex}`;
    list.appendChild(li);
  }
}

/* ---------- Practice ---------- */
function buildScopeOptions() {
  const due = state.data.vocab.filter((v) => isDue(v.rank)).length;
  let html = `<option value="due">Due (${due})</option>
    <option value="all">All words (${state.data.vocab.length})</option>`;
  for (const l of lessons()) html += `<option value="lesson:${l.n}">Lesson ${l.n} (${l.items.length})</option>`;
  const sel = $("#scope");
  sel.innerHTML = html;
  if (![...sel.options].some((o) => o.value === state.scope)) state.scope = "due";
  sel.value = state.scope;
}
function pool() {
  if (state.scope === "all") return state.data.vocab.slice();
  if (state.scope.startsWith("lesson:")) {
    const n = Number(state.scope.split(":")[1]);
    const l = lessons().find((x) => x.n === n);
    return l ? l.items.slice() : [];
  }
  return state.data.vocab.filter((v) => isDue(v.rank));
}
function buildDeck() {
  let d = pool();
  d.sort((a, b) => a.rank - b.rank);
  if (state.shuffle) shuffle(d);
  state.deck = d;
  state.deckPos = 0;
  state.flipped = false;
  state.quizPicked = null;
  buildScopeOptions();
  renderPractice();
}
function shuffle(a) { for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }
const currentCard = () => state.deck[state.deckPos];

function renderPractice() {
  const card = currentCard();
  const done = !card;
  const quiz = state.mode === "quiz";

  $("#study-done").hidden = !done;
  $("#card").style.visibility = done ? "hidden" : "visible";
  $("#study-count").textContent = done
    ? (state.scope === "due" ? "Nothing due right now." : "0 left")
    : `${state.deckPos + 1} / ${state.deck.length} · mode: ${state.mode}`;

  // actions
  $("#study-actions").hidden = done || quiz;
  $("#next-btn").hidden = !(quiz && state.quizPicked);
  $("#quiz-options").hidden = !(quiz && !done);
  if (done) return;

  const front = card.word;
  if (state.mode === "production") {
    $("#front-main").className = "card-prompt";
    $("#front-main").textContent = card.meaning;
    $("#front-sub").textContent = "";
    $("#front-hint").textContent = "tap to reveal the word";
  } else {
    $("#front-main").className = "card-word" + (isCJK(front) ? " card-cjk" : "");
    $("#front-main").textContent = front;
    $("#front-sub").innerHTML = toneHTML(card.pinyinParts, "") || esc(card.pinyin);
    $("#front-hint").textContent = "tap to reveal";
  }
  fillSpeakbar($("#front-speak"), [{ text: card.word, label: "Word" }]);
  $("#front-zhuyin").innerHTML = toneHTML(card.zhuyinParts, " ") || esc(card.zhuyin);
  // Reading on the hidden side: user choice, but never in Produce (it is the answer)
  const showFrontPron = state.mode !== "production" && state.frontPron === "show";
  $("#front-zhuyin").hidden = !showFrontPron;
  $("#front-sub").hidden = !showFrontPron;
  $("#front-hint").hidden = quiz;

  $("#back-word").textContent = card.word;
  $("#back-zhuyin").innerHTML = toneHTML(card.zhuyinParts, " ") || esc(card.zhuyin);
  $("#back-pinyin").innerHTML = toneHTML(card.pinyinParts, "") || esc(card.pinyin);
  $("#back-meaning").textContent = card.meaning;
  $("#back-example").textContent = card.example;
  fillSpeakbar($("#back-speak"), [
    { text: card.word, label: "Word" },
    { text: card.example, label: "Sentence" },
  ]);

  if (quiz) {
    $(".front").hidden = false;
    $(".back").hidden = true;
    renderQuiz(card);
  } else {
    $(".front").hidden = state.flipped;
    $(".back").hidden = !state.flipped;
  }
}

function renderQuiz(card) {
  const opts = $("#quiz-options");
  if (state.quizPicked) {
    // reveal result: show back details + Next
    $(".front").hidden = true;
    $(".back").hidden = false;
    return;
  }
  opts.innerHTML = "";
  const poolMeanings = state.data.vocab.filter((v) => v.rank !== card.rank);
  shuffle(poolMeanings);
  const choices = [{ v: card, ok: true }];
  const seen = new Set([card.meaning]);
  for (const v of poolMeanings) {
    if (choices.length >= 4) break;
    if (seen.has(v.meaning)) continue;
    seen.add(v.meaning);
    choices.push({ v, ok: false });
  }
  shuffle(choices);
  for (const c of choices) {
    const b = document.createElement("button");
    b.className = "quiz-option";
    b.type = "button";
    b.textContent = c.v.meaning;
    b.dataset.rank = c.v.rank;
    b.addEventListener("click", () => answerQuiz(card, c.ok, b));
    opts.appendChild(b);
  }
}
function answerQuiz(card, ok, btn) {
  if (state.quizPicked) return;
  state.quizPicked = ok ? "good" : "again";
  grade(card.rank, ok ? "good" : "again");
  for (const b of $$("#quiz-options .quiz-option")) {
    if (Number(b.dataset.rank) === card.rank) b.classList.add("correct");
    else if (b === btn) b.classList.add("wrong");
    b.disabled = true;
  }
  speak(card.word);
  renderPractice();
}

function flip() {
  if (state.mode === "quiz") return;
  state.flipped = !state.flipped;
  if (state.flipped) speak(currentCard().word);
  renderPractice();
}
function advance(g) {
  const c = currentCard();
  if (c && g) grade(c.rank, g);
  state.deckPos += 1;
  state.flipped = false;
  state.quizPicked = null;
  renderPractice();
}
function goNext() {
  if (state.deckPos < state.deck.length) { state.deckPos += 1; state.flipped = false; state.quizPicked = null; renderPractice(); }
}
function goPrev() {
  if (state.deckPos > 0) { state.deckPos -= 1; state.flipped = false; state.quizPicked = null; renderPractice(); }
}

/* ---------- Progress ---------- */
const BANDS = [100, 300, 1000, 2000];
function renderProgress() {
  const total = state.data.vocab.length;
  const known = knownIn(state.data.vocab);
  const isnew = state.data.vocab.filter((v) => isNew(v.rank)).length;
  const due = state.data.vocab.filter((v) => isDue(v.rank)).length;
  const pct = total ? Math.round((known / total) * 100) : 0;

  const bands = BANDS.map((b) => {
    const inBand = state.data.vocab.filter((v) => v.rank <= b);
    const k = knownIn(inBand);
    const p = inBand.length ? Math.round((k / inBand.length) * 100) : 0;
    return `<tr><td>top ${b}</td><td>${inBand.length} in list</td><td>${k} known</td><td>${p}%</td></tr>`;
  }).join("");

  const lessonRows = lessons().map((l) => {
    const k = knownIn(l.items);
    return `<tr><td>Lesson ${l.n}</td><td>${l.items.length} words</td><td>${k} known</td>
      <td>${Math.round((k / l.items.length) * 100)}%</td></tr>`;
  }).join("");

  $("#progress").innerHTML = `
    <div class="stat-grid">
      <div class="stat"><div class="k">due now</div><div class="v">${due}</div></div>
      <div class="stat"><div class="k">new</div><div class="v">${isnew}</div></div>
      <div class="stat"><div class="k">known</div><div class="v">${known}</div></div>
      <div class="stat"><div class="k">list covered</div><div class="v">${pct}%</div></div>
    </div>
    <div class="bar hero-bar"><span style="width:${pct}%"></span></div>
    <h2 class="section">Frequency bands</h2>
    <table class="bands"><thead><tr><th>band</th><th>available</th><th>known</th><th>covered</th></tr></thead>
      <tbody>${bands}</tbody></table>
    <h2 class="section">Lessons</h2>
    <table class="bands"><thead><tr><th>lesson</th><th>size</th><th>known</th><th>done</th></tr></thead>
      <tbody>${lessonRows}</tbody></table>`;
}

/* ---------- Navigation ---------- */
const VIEWS = ["learn", "practice", "progress"];
function showView(name) {
  state.view = name;
  for (const t of $$(".tab")) t.classList.toggle("is-active", t.dataset.tab === name);
  for (const v of VIEWS) $(`#view-${v}`).hidden = v !== name;
  if (name === "practice") buildDeck();
  if (name === "progress") renderProgress();
  if (name === "learn") { renderLearnVocab(); renderPatterns(); renderLearnZhuyin(); }
}
function setLearnTab(tab) {
  state.learnTab = tab;
  for (const s of $$(".seg")) s.classList.toggle("is-active", s.dataset.learn === tab);
  $("#learn-vocab").hidden = tab !== "vocab";
  $("#learn-zhuyin").hidden = tab !== "zhuyin";
  $("#learn-patterns").hidden = tab !== "patterns";
  if (tab === "zhuyin") renderLearnZhuyin();
}

function renderLearnZhuyin() {
  const el = $("#zhuyin-ref");
  const groups = state.data.zhuyin || [];
  if (!groups.length) {
    el.innerHTML = `<p class="meta">No Zhuyin reference for this language.</p>`;
    return;
  }
  el.innerHTML = groups.map((g) => {
    const grid = g.symbols.length
      ? `<div class="zh-grid">${g.symbols.map((s) => `
          <div class="zh-cell">
            <span class="zh-sym">${esc(s.symbol)}</span>
            <span class="zh-pin">${esc(s.pinyin)}</span>
            ${s.note ? `<span class="zh-note">${esc(s.note)}</span>` : ""}
          </div>`).join("")}</div>`
      : "";
    const bullets = g.bullets.length
      ? `<ul class="zh-bullets">${g.bullets.map((b) => `<li>${esc(b)}</li>`).join("")}</ul>`
      : "";
    return `<h2 class="section">${esc(g.name)}</h2>${grid}${bullets}`;
  }).join("");
}

/* ---------- Boot ---------- */
async function setLang(lang) {
  state.lang = lang;
  state.data = await fetchJSON(`data/${lang}.json`);
  load(lang);
  state.scope = "due";
  document.title = `Tawki — ${state.data.title}`;
  buildScopeOptions();
  renderLearnVocab();
  renderPatterns();
  renderProgress();
  buildDeck();
}
async function fetchJSON(url) {
  const r = await fetch(url, { cache: "no-store" });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
}

async function boot() {
  pickVoice();
  if ("speechSynthesis" in window) speechSynthesis.onvoiceschanged = pickVoice;
  loadNotation();
  applyNotation();
  loadFrontPron();
  applyFrontPron();

  // Offline support (http/https only)
  if ("serviceWorker" in navigator && location.protocol.startsWith("http")) {
    navigator.serviceWorker.register("sw.js").catch(() => {});
  }

  const index = await fetchJSON("data/index.json").catch(() => null);
  const langs = ((index && index.languages) || ["zh-tw"]).filter((l) => l !== "index");
  if (!langs.length) langs.push("zh-tw");
  const sel = $("#lang");
  sel.innerHTML = langs.map((l) => `<option value="${l}">${l}</option>`).join("");
  sel.addEventListener("change", () => setLang(sel.value).then(() => showView("learn")));
  await setLang(langs[0]);

  // Deep links: ?lang=zh-tw&scope=lesson:1&mode=quiz
  const params = new URLSearchParams(location.search);
  const pLang = params.get("lang");
  if (pLang && langs.includes(pLang) && pLang !== state.lang) { sel.value = pLang; await setLang(pLang); }
  const pScope = params.get("scope");
  if (pScope) state.scope = pScope;
  const pMode = params.get("mode");
  if (pMode && ["recognition", "production", "quiz"].includes(pMode)) { state.mode = pMode; $("#mode").value = pMode; }
  const deep = Boolean(pScope || pMode);

  for (const s of $$(".seg")) s.addEventListener("click", () => setLearnTab(s.dataset.learn));
  $("#notation").addEventListener("change", (e) => {
    state.notation = e.target.value;
    localStorage.setItem(NOTATION_KEY, state.notation);
    applyNotation();
  });
  $("#search").addEventListener("input", (e) => { state.query = e.target.value; renderLearnVocab(); });
  $("#hide-known").addEventListener("click", (e) => {
    state.hideKnown = !state.hideKnown;
    e.currentTarget.setAttribute("aria-pressed", String(state.hideKnown));
    renderLearnVocab();
  });
  $("#scope").addEventListener("change", (e) => { state.scope = e.target.value; state.deckPos = 0; state.flipped = false; state.quizPicked = null; buildDeck(); });
  $("#mode").addEventListener("change", (e) => { state.mode = e.target.value; state.flipped = false; state.quizPicked = null; renderPractice(); });
  $("#front-pron").addEventListener("click", () => {
    state.frontPron = state.frontPron === "show" ? "hide" : "show";
    localStorage.setItem(FRONT_PRON_KEY, state.frontPron);
    applyFrontPron();
    renderPractice();
  });
  $("#study-shuffle").addEventListener("click", (e) => {
    state.shuffle = !state.shuffle;
    e.currentTarget.setAttribute("aria-pressed", String(state.shuffle));
    buildDeck();
  });
  for (const g of $$("#study-actions .btn")) g.addEventListener("click", () => advance(g.dataset.grade));
  $("#next-btn").addEventListener("click", () => advance(null));

  // Flashcard: tap = reveal, horizontal swipe = prev/next, arrows/space on keyboard
  const card = $("#card");
  let dragging = false, sx = 0, sy = 0, swiped = false;
  card.addEventListener("pointerdown", (e) => { dragging = true; sx = e.clientX; sy = e.clientY; swiped = false; });
  window.addEventListener("pointerup", (e) => {
    if (!dragging) return;
    dragging = false;
    const dx = e.clientX - sx, dy = e.clientY - sy;
    if (Math.abs(dx) > 40 && Math.abs(dx) > Math.abs(dy)) {
      swiped = true;
      if (dx < 0) goNext(); else goPrev();
    }
  });
  card.addEventListener("click", () => { if (swiped) { swiped = false; return; } flip(); });
  window.addEventListener("keydown", (e) => {
    if (state.view !== "practice") return;
    if (e.key === "ArrowRight") goNext();
    else if (e.key === "ArrowLeft") goPrev();
    else if (e.key === " " || e.key === "Enter") { e.preventDefault(); if (state.mode === "quiz") return; flip(); }
  });

  $("#reset").addEventListener("click", () => {
    if (!confirm("Reset all progress for this language?")) return;
    state.sched = {};
    save();
    renderLearnVocab();
    renderProgress();
    buildScopeOptions();
    buildDeck();
  });
  $("#export-progress").addEventListener("click", exportProgress);
  $("#import-file").addEventListener("change", (e) => {
    const file = e.target.files && e.target.files[0];
    if (file) importProgress(file);
  });
  for (const t of $$(".tab")) t.addEventListener("click", () => showView(t.dataset.tab));

  showView(deep ? "practice" : "learn");
}

boot().catch((err) => {
  $("#app").innerHTML =
    `<p class="meta">Could not load data: ${esc(err.message)}. Serve over HTTP, e.g. <code>python3 -m http.server -d web</code>.</p>`;
});
