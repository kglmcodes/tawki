/* Tawki — mobile-first study UI. Vanilla JS, offline-capable.
   Data: web/data/index.json + web/data/<lang>.json (generated by scripts/build_data.py) */

const LESSON_SIZE = 20;

const state = {
  lang: null,
  data: null,
  known: new Set(),
  view: "learn",
  learnTab: "vocab",
  query: "",
  hideKnown: false,
  scope: "unseen",      // "unseen" | "all" | "lesson:<n>"
  shuffle: false,
  deck: [],
  deckPos: 0,
  flipped: false,
};

const $ = (s) => document.querySelector(s);
const $$ = (s) => document.querySelectorAll(s);
const key = (lang) => `tawki:${lang}`;
const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) =>
  ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

function load(lang) {
  try {
    const raw = JSON.parse(localStorage.getItem(key(lang)) || "{}");
    state.known = new Set(raw.known || []);
  } catch { state.known = new Set(); }
}
function save() {
  localStorage.setItem(key(state.lang), JSON.stringify({ known: [...state.known] }));
}
async function fetchJSON(url) {
  const r = await fetch(url, { cache: "no-store" });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
}
function shuffle(a) {
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
const isCJK = (s) => /[\u3400-\u9FFF\uF900-\uFAFF]/.test(s);
const wordClass = (w) => "word" + (isCJK(w) ? " word-cjk" : "");

/* Lessons = chunks of the frequency list */
function lessons() {
  const out = [];
  for (let i = 0; i < state.data.vocab.length; i += LESSON_SIZE) {
    out.push({ n: out.length + 1, items: state.data.vocab.slice(i, i + LESSON_SIZE) });
  }
  return out;
}
const knownIn = (items) => items.filter((v) => state.known.has(v.rank)).length;

/* ---------------- Learn / Vocabulary ---------------- */
function renderLearnVocab() {
  const grid = $("#lesson-grid");
  const list = $("#vocab-list");
  const meta = $("#browse-meta");
  const q = state.query.trim().toLowerCase();

  if (q) {
    grid.hidden = true;
    list.hidden = false;
    const items = state.data.vocab.filter((v) =>
      !(state.hideKnown && state.known.has(v.rank)) &&
      (v.word + " " + v.pinyin + " " + v.meaning).toLowerCase().includes(q));
    list.innerHTML = "";
    for (const v of items) list.appendChild(vocabCard(v));
    meta.textContent = `${items.length} match · ${state.known.size}/${state.data.vocab.length} known`;
    return;
  }

  list.hidden = true;
  grid.hidden = false;
  meta.textContent = `${state.known.size}/${state.data.vocab.length} known`;
  grid.innerHTML = "";
  for (const l of lessons()) {
    const k = knownIn(l.items);
    const pct = Math.round((k / l.items.length) * 100);
    const b = document.createElement("button");
    b.className = "lesson" + (k === l.items.length ? " is-done" : "");
    b.innerHTML = `
      <div class="lesson-top"><span class="lesson-no">Lesson ${l.n}</span>
        <span class="lesson-count">${k}/${l.items.length}</span></div>
      <div class="lesson-sample">${l.items.slice(0, 5).map((v) => esc(v.word)).join(" ")}</div>
      <div class="bar"><span style="width:${pct}%"></span></div>`;
    b.addEventListener("click", () => startLesson(l.n));
    grid.appendChild(b);
  }
}

function vocabCard(v) {
  const li = document.createElement("li");
  li.className = "card vocab-row" + (state.known.has(v.rank) ? " is-known" : "");
  li.innerHTML = `
    <span class="rank">${v.rank}</span>
    <div class="vocab-main">
      <div><span class="${wordClass(v.word)}">${esc(v.word)}</span>
        <span class="pinyin">${esc(v.pinyin)}</span></div>
      <div>${esc(v.meaning)}</div>
      <div class="example">${esc(v.example)}</div>
    </div>
    <button class="mark" title="Toggle known" aria-label="Toggle known">&#10003;</button>`;
  const toggle = () => {
    if (state.known.has(v.rank)) state.known.delete(v.rank); else state.known.add(v.rank);
    save();
    renderLearnVocab();
    if (state.view === "progress") renderProgress();
  };
  li.querySelector(".mark").addEventListener("click", (e) => { e.stopPropagation(); toggle(); });
  li.addEventListener("click", toggle);
  return li;
}

/* ---------------- Learn / Patterns ---------------- */
function renderPatterns() {
  const list = $("#pattern-list");
  list.innerHTML = "";
  for (const p of state.data.patterns) {
    const li = document.createElement("li");
    li.className = "card";
    const ex = p.examples.length
      ? `<ul class="pattern-examples">${p.examples.map((e) => `<li>${esc(e)}</li>`).join("")}</ul>`
      : "";
    li.innerHTML = `
      <div class="pattern-head"><span class="pattern-num">${p.n}</span>
        <span class="pattern-name">${esc(p.name)}</span></div>
      ${p.does ? `<div>${esc(p.does)}</div>` : ""}
      ${p.structure ? `<div class="pattern-structure">${esc(p.structure)}</div>` : ""}
      ${ex}`;
    list.appendChild(li);
  }
}

/* ---------------- Practice ---------------- */
function buildScopeOptions() {
  const sel = $("#scope");
  const unseen = state.data.vocab.filter((v) => !state.known.has(v.rank)).length;
  let html = `<option value="unseen">Unseen (${unseen})</option>
    <option value="all">All words (${state.data.vocab.length})</option>`;
  for (const l of lessons()) {
    html += `<option value="lesson:${l.n}">Lesson ${l.n} (${l.items.length})</option>`;
  }
  sel.innerHTML = html;
  sel.value = state.scope;
}

function pool() {
  if (state.scope === "all") return state.data.vocab.slice();
  if (state.scope.startsWith("lesson:")) {
    const n = Number(state.scope.split(":")[1]);
    const l = lessons().find((x) => x.n === n);
    return l ? l.items.slice() : [];
  }
  return state.data.vocab.filter((v) => !state.known.has(v.rank));
}

function buildDeck() {
  let d = pool();
  if (state.shuffle) shuffle(d);
  state.deck = d;
  state.deckPos = 0;
  state.flipped = false;
  renderPractice();
}

function currentCard() { return state.deck[state.deckPos]; }

function renderPractice() {
  const card = currentCard();
  const done = !card;
  $("#study-done").hidden = !done;
  $("#card").style.visibility = done ? "hidden" : "visible";
  $("#study-actions").style.visibility = done ? "hidden" : "visible";
  $("#study-count").textContent = done ? "0 left"
    : `${state.deck.length - state.deckPos} left of ${state.deck.length}`;
  if (done) return;
  $("#card-word").textContent = card.word;
  $("#card-pinyin").textContent = card.pinyin;
  $("#card-meaning").textContent = card.meaning;
  $("#card-example").textContent = card.example;
  $(".front").hidden = state.flipped;
  $(".back").hidden = !state.flipped;
}

function flip() { state.flipped = !state.flipped; renderPractice(); }
function advance(markKnown) {
  const c = currentCard();
  if (c && markKnown) { state.known.add(c.rank); save(); }
  state.deckPos += 1;
  state.flipped = false;
  renderPractice();
}

function startLesson(n) {
  state.scope = `lesson:${n}`;
  buildScopeOptions();
  showView("practice");
}

/* ---------------- Progress ---------------- */
const BANDS = [100, 300, 1000, 2000];
function renderProgress() {
  const total = state.data.vocab.length;
  const known = state.known.size;
  const pct = total ? Math.round((known / total) * 100) : 0;

  const bands = BANDS.map((b) => {
    const inBand = state.data.vocab.filter((v) => v.rank <= b);
    const k = knownIn(inBand);
    const p = inBand.length ? Math.round((k / inBand.length) * 100) : 0;
    return `<tr><td>top ${b}</td><td>${inBand.length} in list</td><td>${k} known</td><td>${p}%</td></tr>`;
  }).join("");

  const lessonRows = lessons().map((l) => {
    const k = knownIn(l.items);
    return `<tr><td>Lesson ${l.n}</td><td>${l.items.length} words</td><td>${k} known</td>
      <td>${Math.round((k / l.items.length) * 100)}%</td></tr>`;
  }).join("");

  $("#progress").innerHTML = `
    <div class="stat-grid">
      <div class="stat"><div class="k">known</div><div class="v">${known}</div></div>
      <div class="stat"><div class="k">in list</div><div class="v">${total}</div></div>
      <div class="stat"><div class="k">list covered</div><div class="v">${pct}%</div></div>
      <div class="stat"><div class="k">patterns</div><div class="v">${state.data.patterns.length}</div></div>
    </div>
    <div class="bar hero-bar"><span style="width:${pct}%"></span></div>
    <h2 class="section">Frequency bands</h2>
    <table class="bands"><thead><tr><th>band</th><th>available</th><th>known</th><th>covered</th></tr></thead>
      <tbody>${bands}</tbody></table>
    <h2 class="section">Lessons</h2>
    <table class="bands"><thead><tr><th>lesson</th><th>size</th><th>known</th><th>done</th></tr></thead>
      <tbody>${lessonRows}</tbody></table>`;
}

/* ---------------- Navigation ---------------- */
const VIEWS = ["learn", "practice", "progress"];
function showView(name) {
  state.view = name;
  for (const t of $$(".tab")) t.classList.toggle("is-active", t.dataset.tab === name);
  for (const v of VIEWS) $(`#view-${v}`).hidden = v !== name;
  if (name === "practice") buildDeck();
  if (name === "progress") renderProgress();
  if (name === "learn") { renderLearnVocab(); renderPatterns(); }
}
function setLearnTab(tab) {
  state.learnTab = tab;
  for (const s of $$(".seg")) s.classList.toggle("is-active", s.dataset.learn === tab);
  $("#learn-vocab").hidden = tab !== "vocab";
  $("#learn-patterns").hidden = tab !== "patterns";
}

/* ---------------- Boot ---------------- */
async function setLang(lang) {
  state.lang = lang;
  state.data = await fetchJSON(`data/${lang}.json`);
  load(lang);
  state.scope = "unseen";
  document.title = `Tawki — ${state.data.title}`;
  buildScopeOptions();
  renderLearnVocab();
  renderPatterns();
  renderProgress();
  buildDeck();
}

async function boot() {
  const index = await fetchJSON("data/index.json").catch(() => null);
  const langs = (index && index.languages) || ["zh-tw"];
  const sel = $("#lang");
  sel.innerHTML = langs.map((l) => `<option value="${l}">${l}</option>`).join("");
  sel.addEventListener("change", () => setLang(sel.value).then(() => showView("learn")));
  await setLang(langs[0]);

  for (const s of $$(".seg")) s.addEventListener("click", () => setLearnTab(s.dataset.learn));
  $("#search").addEventListener("input", (e) => { state.query = e.target.value; renderLearnVocab(); });
  $("#hide-known").addEventListener("click", (e) => {
    state.hideKnown = !state.hideKnown;
    e.currentTarget.setAttribute("aria-pressed", String(state.hideKnown));
    renderLearnVocab();
  });
  $("#scope").addEventListener("change", (e) => { state.scope = e.target.value; buildDeck(); });
  $("#study-shuffle").addEventListener("click", (e) => {
    state.shuffle = !state.shuffle;
    e.currentTarget.setAttribute("aria-pressed", String(state.shuffle));
    buildDeck();
  });
  $("#card").addEventListener("click", flip);
  $("#btn-again").addEventListener("click", () => advance(false));
  $("#btn-know").addEventListener("click", () => advance(true));
  $("#reset").addEventListener("click", () => {
    if (!confirm("Reset all progress for this language?")) return;
    state.known = new Set();
    save();
    renderLearnVocab();
    renderProgress();
    buildScopeOptions();
    buildDeck();
  });
  for (const t of $$(".tab")) t.addEventListener("click", () => showView(t.dataset.tab));

  showView("learn");
}

boot().catch((err) => {
  $("#app").innerHTML =
    `<p class="meta">Could not load data: ${esc(err.message)}. Serve over HTTP, e.g. <code>python3 -m http.server -d web</code>.</p>`;
});
