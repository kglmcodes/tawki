/* Tawki — mobile-first study UI. Vanilla JS, offline-capable.
   Data: web/data/index.json + web/data/<lang>.json (generated by scripts/build_data.py) */

const state = {
  lang: null,
  data: null,
  known: new Set(),
  hideKnown: false,
  studyScope: "unseen", // "unseen" | "all"
  studyShuffle: false,
  deck: [],
  deckPos: 0,
  flipped: false,
};

const $ = (sel) => document.querySelector(sel);

function storageKey(lang) { return `tawki:${lang}`; }

function load(lang) {
  try {
    const raw = JSON.parse(localStorage.getItem(storageKey(lang)) || "{}");
    state.known = new Set(raw.known || []);
  } catch { state.known = new Set(); }
}

function save() {
  localStorage.setItem(storageKey(state.lang),
    JSON.stringify({ known: [...state.known] }));
}

async function fetchJSON(url) {
  const r = await fetch(url, { cache: "no-store" });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
}

function shuffle(a) {
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function isCJK(s) { return /[\u3400-\u9FFF\uF900-\uFAFF]/.test(s); }

/* ---------------- Browse ---------------- */
function renderBrowse() {
  const list = $("#vocab-list");
  const q = $("#search").value.trim().toLowerCase();
  const items = state.data.vocab.filter((v) => {
    if (state.hideKnown && state.known.has(v.rank)) return false;
    if (!q) return true;
    return (v.word + " " + v.pinyin + " " + v.meaning).toLowerCase().includes(q);
  });

  list.innerHTML = "";
  for (const v of items) {
    const li = document.createElement("li");
    li.className = "card vocab-row" + (state.known.has(v.rank) ? " is-known" : "");
    li.innerHTML = `
      <span class="rank">${v.rank}</span>
      <div class="vocab-main">
        <div>
          <span class="word${isCJK(v.word) ? " word-cjk" : ""}">${v.word}</span>
          <span class="pinyin">${v.pinyin}</span>
        </div>
        <div class="meaning">${v.meaning}</div>
        <div class="example">${v.example}</div>
      </div>
      <button class="mark" title="Toggle known" aria-label="Toggle known">&#10003;</button>`;
    li.querySelector(".mark").addEventListener("click", (e) => {
      e.stopPropagation();
      if (state.known.has(v.rank)) state.known.delete(v.rank);
      else state.known.add(v.rank);
      save();
      renderBrowse();
      if (!$("#view-progress").hidden) renderProgress();
    });
    li.addEventListener("click", () => {
      if (state.known.has(v.rank)) state.known.delete(v.rank);
      else state.known.add(v.rank);
      save();
      renderBrowse();
    });
    list.appendChild(li);
  }
  $("#browse-meta").textContent =
    `${items.length} shown · ${state.known.size}/${state.data.vocab.length} known`;
}

/* ---------------- Study (flashcards) ---------------- */
function buildDeck() {
  let pool = state.data.vocab.slice();
  if (state.studyScope === "unseen") pool = pool.filter((v) => !state.known.has(v.rank));
  if (state.studyShuffle) shuffle(pool);
  state.deck = pool;
  state.deckPos = 0;
  state.flipped = false;
  renderStudy();
}

function currentCard() { return state.deck[state.deckPos]; }

function renderStudy() {
  const card = currentCard();
  const done = !card;
  $("#study-done").hidden = !done;
  $("#card").style.visibility = done ? "hidden" : "visible";
  $("#study-actions").style.visibility = done ? "hidden" : "visible";

  const remaining = state.deck.length - state.deckPos;
  $("#study-count").textContent = done
    ? "0 left"
    : `${remaining} left · scope: ${state.studyScope}`;

  if (done) return;

  $("#card-word").textContent = card.word;
  $("#card-pinyin").textContent = card.pinyin;
  $("#card-meaning").textContent = card.meaning;
  $("#card-example").textContent = card.example;
  $(".front").hidden = state.flipped;
  $(".back").hidden = !state.flipped;
}

function flip() { state.flipped = !state.flipped; renderStudy(); }

function advance(markKnown) {
  const card = currentCard();
  if (card && markKnown) { state.known.add(card.rank); save(); }
  state.deckPos += 1;
  state.flipped = false;
  renderStudy();
}

/* ---------------- Patterns ---------------- */
function renderPatterns() {
  const list = $("#pattern-list");
  list.innerHTML = "";
  for (const p of state.data.patterns) {
    const li = document.createElement("li");
    li.className = "card";
    const ex = p.examples.length
      ? `<ul class="pattern-examples">${p.examples.map((e) => `<li>${e}</li>`).join("")}</ul>`
      : "";
    li.innerHTML = `
      <div class="pattern-head">
        <span class="pattern-num">${p.n}</span>
        <span class="pattern-name">${p.name}</span>
      </div>
      ${p.does ? `<div class="pattern-does">${p.does}</div>` : ""}
      ${p.structure ? `<div class="pattern-structure">${p.structure}</div>` : ""}
      ${ex}`;
    list.appendChild(li);
  }
}

/* ---------------- Progress ---------------- */
const BANDS = [100, 300, 1000, 2000];
function renderProgress() {
  const total = state.data.vocab.length;
  const known = state.known.size;
  const pct = total ? Math.round((known / total) * 100) : 0;

  const rows = BANDS.map((b) => {
    const inBand = state.data.vocab.filter((v) => v.rank <= b);
    const have = inBand.length;
    const k = inBand.filter((v) => state.known.has(v.rank)).length;
    const p = have ? Math.round((k / have) * 100) : 0;
    return `<tr><td>top ${b}</td><td>${have} in list</td><td>${k} known</td><td>${p}%</td></tr>`;
  }).join("");

  $("#progress").innerHTML = `
    <div class="stat-grid">
      <div class="stat"><div class="k">known</div><div class="v">${known}</div></div>
      <div class="stat"><div class="k">in list</div><div class="v">${total}</div></div>
      <div class="stat"><div class="k">list covered</div><div class="v">${pct}%</div></div>
      <div class="stat"><div class="k">patterns</div><div class="v">${state.data.patterns.length}</div></div>
    </div>
    <div class="bar"><span style="width:${pct}%"></span></div>
    <table class="bands">
      <thead><tr><th>band</th><th>available</th><th>known</th><th>covered</th></tr></thead>
      <tbody>${rows}</tbody>
    </table>`;
}

/* ---------------- Tabs ---------------- */
function showTab(name) {
  for (const t of document.querySelectorAll(".tab")) {
    t.classList.toggle("is-active", t.dataset.tab === name);
  }
  for (const v of ["browse", "study", "patterns", "progress"]) {
    $(`#view-${v}`).hidden = v !== name;
  }
  if (name === "study") buildDeck();
  if (name === "progress") renderProgress();
  if (name === "browse") renderBrowse();
  if (name === "patterns") renderPatterns();
}

/* ---------------- Boot ---------------- */
async function boot() {
  const index = await fetchJSON("data/index.json").catch(() => null);
  const langs = (index && index.languages) || ["zh-tw"];
  const sel = $("#lang");
  sel.innerHTML = langs.map((l) => `<option value="${l}">${l}</option>`).join("");

  async function setLang(lang) {
    state.lang = lang;
    state.data = await fetchJSON(`data/${lang}.json`);
    load(lang);
    $("#title")?.remove?.();
    document.title = `Tawki — ${state.data.title}`;
    buildDeck();
    renderBrowse();
    renderPatterns();
    renderProgress();
  }

  sel.addEventListener("change", () => setLang(sel.value));
  await setLang(langs[0]);

  // Events
  $("#search").addEventListener("input", renderBrowse);
  $("#hide-known").addEventListener("click", (e) => {
    state.hideKnown = !state.hideKnown;
    e.currentTarget.setAttribute("aria-pressed", String(state.hideKnown));
    renderBrowse();
  });
  $("#study-scope").addEventListener("click", (e) => {
    state.studyScope = state.studyScope === "unseen" ? "all" : "unseen";
    e.currentTarget.textContent = state.studyScope === "unseen" ? "Unseen only" : "All words";
    e.currentTarget.setAttribute("aria-pressed", String(state.studyScope === "unseen"));
    buildDeck();
  });
  $("#study-shuffle").addEventListener("click", () => {
    state.studyShuffle = !state.studyShuffle;
    buildDeck();
  });
  $("#card").addEventListener("click", flip);
  $("#btn-again").addEventListener("click", () => advance(false));
  $("#btn-know").addEventListener("click", () => advance(true));
  $("#reset").addEventListener("click", () => {
    if (!confirm("Reset all progress for this language?")) return;
    state.known = new Set();
    save();
    renderBrowse();
    renderProgress();
    buildDeck();
  });
  for (const t of document.querySelectorAll(".tab")) {
    t.addEventListener("click", () => showTab(t.dataset.tab));
  }
  showTab("browse");
}

boot().catch((err) => {
  $("#app").innerHTML =
    `<p class="meta">Could not load data: ${err.message}. Serve over HTTP, e.g. <code>python3 -m http.server -d web</code>.</p>`;
});
